def _bits(glyph: Image.Image) -> str:
    image = glyph.resize((_W, _H), Image.Resampling.NEAREST)
    pixels = image.load()
    return "".join(
        "1" if pixels[x, y] > 128 else "0" for y in range(_H) for x in range(_W)
    )


def _glyphs(image: Image.Image) -> list[Image.Image]:
    width, height = image.size
    pixels = image.convert("RGB").load()
    ink = [[False] * width for _ in range(height)]
    for y in range(height):
        for x in range(width):
            red, green, blue = pixels[x, y]
            _hue, sat, val = colorsys.rgb_to_hsv(red / 255, green / 255, blue / 255)
            if val >= 0.75 and sat <= 0.35:
                ink[y][x] = True
    seen = [[False] * width for _ in range(height)]
    keep = [[False] * width for _ in range(height)]
    for y in range(height):
        for x in range(width):
            if not ink[y][x] or seen[y][x]:
                continue
            stack = [(x, y)]
            seen[y][x] = True
            points = []
            while stack:
                cx, cy = stack.pop()
                points.append((cx, cy))
                for nx, ny in ((cx - 1, cy), (cx + 1, cy), (cx, cy - 1), (cx, cy + 1)):
                    if 0 <= nx < width and 0 <= ny < height and ink[ny][nx] and not seen[ny][nx]:
                        seen[ny][nx] = True
                        stack.append((nx, ny))
            if len(points) < 8:
                continue
            xs = [pt[0] for pt in points]
            ys = [pt[1] for pt in points]
            cx = (min(xs) + max(xs)) / 2
            cy = (min(ys) + max(ys)) / 2
            if max(ys) - min(ys) + 1 < 6:
                continue
            if max(xs) - min(xs) + 1 > 26:
                continue
            if cx < width * 0.18 or cx > width * 0.82 or cy < height * 0.12 or cy > height * 0.88:
                continue
            for px, py in points:
                keep[py][px] = True
    counts = [sum(1 for y in range(height) if keep[y][x]) for x in range(width)]
    cols = [count > 0 for count in counts]
    raw = []
    x = 0
    while x < width:
        if not cols[x]:
            x += 1
            continue
        x0 = x
        while x < width and cols[x]:
            x += 1
        if x - x0 >= 2:
            raw.append((x0, x))
    pieces = []
    for start, end in raw:
        if end - start >= 14:
            mid0 = start + (end - start) // 3
            mid1 = end - (end - start) // 3
            cut = min(range(mid0, max(mid0 + 1, mid1)), key=lambda i: counts[i])
            pieces.append((start, cut))
            pieces.append((cut, end))
        else:
            pieces.append((start, end))
    glyphs = []
    for start, end in pieces:
        if end - start < 2:
            continue
        ys = [y for y in range(height) for x in range(start, end) if keep[y][x]]
        if not ys:
            continue
        top, bottom = min(ys), max(ys) + 1
        glyph = Image.new("L", (end - start, bottom - top), 0)
        target = glyph.load()
        for y in range(top, bottom):
            for x in range(start, end):
                if keep[y][x]:
                    target[x - start, y - top] = 255
        if glyph.height > int(glyph.width * 1.6):
            rows = [sum(1 for x in range(glyph.width) if target[x, y] > 0) for y in range(glyph.height)]
            window = min(glyph.height, max(glyph.width, int(glyph.width * 1.3)))
            best_y = 0
            best_n = -1
            for y0 in range(glyph.height - window + 1):
                total = sum(rows[y0 : y0 + window])
                if total > best_n:
                    best_n = total
                    best_y = y0
            glyph = glyph.crop((0, best_y, glyph.width, best_y + window))
        glyphs.append(glyph)
    if len(glyphs) > 2:
        tall = max(glyph.height for glyph in glyphs)
        glyphs = [glyph for glyph in glyphs if glyph.height >= tall * 0.7]
    return glyphs


def read_timer_digits(image: Image.Image) -> str | None:
    side = max(image.width, image.height)
    if side < 40 or side > 60:
        image = image.resize((50, 50), Image.Resampling.BOX)
    found = _glyphs(image)
    if not found or len(found) > 2:
        return None
    chars = []
    for glyph in found:
        row = _bits(glyph)
        best_digit = ""
        best_dist = _MAX_DIST + 1
        for digit, samples in _SAMPLES.items():
            for sample in samples:
                dist = sum(left != right for left, right in zip(row, sample))
                if dist < best_dist:
                    best_dist = dist
                    best_digit = digit
        if not best_digit or best_dist > _MAX_DIST:
            return None
        chars.append(best_digit)
    return "".join(chars)

